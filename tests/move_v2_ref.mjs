// The Move screen mockups' reference hashes (FNV-1a over the 128 x 64 pixels, 0 / 1 a byte) and, with a second
// argument, each screen as a PBM in that folder. Usage: node move_v2_ref.mjs <mockup.html> [pbm-dir]
//   V2Screen.dc.html (the v2 design canvas: every screen in its S)          -> tests/move_v2_ref.h,  <name>.pbm
//   move-firmware-browser-mockup.html (0.4.0: its gallery's screens, its renderer, its catalog data)
//                                                                           -> tests/move_fwb_ref.h, fwb.<name>.pbm,
//                                                                              tests/move_fwb_data.h (the catalog)
// The firmware browser's mockup draws font5x7's rows 0..6 only; the core draws the font's 8-row cell (descenders),
// so the reference is made with 8 rows as well.
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
const html = readFileSync(process.argv[2], "utf8");
const here = dirname(fileURLToPath(import.meta.url));
const fnv = (b) => { let h = 0x811c9dc5; for (const v of b) h = Math.imul(h ^ v, 0x01000193) >>> 0; return h; };
const pbm = (b, W, H) => { let s = `P1\n${W} ${H}\n`; for (let y = 0; y < H; y++) s += Array.from(b.slice(y * W, y * W + W)).join(" ") + "\n"; return s; };

if (html.includes("const DATA = ")) {
  // ---- the firmware browser (0.4.0)
  const a = html.indexOf("const DATA = "), b = html.indexOf("// ---------- surface ----------");
  const g0 = html.indexOf("const G=", html.indexOf("// ---------- gallery ----------")), g1 = html.indexOf("// ---------- banks ----------");
  let js = html.slice(a, b).replace("for(let r=0;r<7;r++)", "for(let r=0;r<8;r++)");
  const fxs = html.slice(html.indexOf("const FXS="), html.indexOf("\n", html.indexOf("const FXS=")));
  js += "\n" + fxs + "\nconst __shots=[]; function shot(t,x,mut){ __shots.push([t,mut]); }\n" + html.slice(g0, g1);
  js += "\nfunction __run(mut){ const st=fresh(); mut(st); const save=S; S=st; const g=render(st); S=save; return g.b; }";
  const { __shots, __run, W, H, DATA, ascii, FAV0, INSTALLED0, OLDVER, NEWFW } =
    new Function(js + "\nreturn { __shots, __run, W, H, DATA, ascii, FAV0, INSTALLED0, OLDVER, NEWFW };")();
  const rows = [], seen = new Set();
  for (const [t, mut] of __shots) {
    let n = "fwb." + t.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
    while (seen.has(n)) n += "2";
    seen.add(n);
    const px = __run(mut);
    rows.push(`    { "${n}", 0x${fnv(px).toString(16).padStart(8, "0")}u },`);
    if (process.argv[3]) writeFileSync(join(process.argv[3], `${n}.pbm`), pbm(px, W, H));
  }
  writeFileSync(join(here, "move_fwb_ref.h"), `/* generated by move_v2_ref.mjs from move-firmware-browser-mockup.html: do not edit */
static const struct { const char *name; uint32_t hash; } FWB_REF[] = {
${rows.join("\n")}
};
`);
  // the catalog as a host would give it (ASCII: the mockup's ascii()), thumbnails for the firmwares the shots show
  const THUMBS = new Set(["sloop", "melodee", "choralroot", "golf", "elasticat", "felucca", "karma", NEWFW.id]);
  const CATS = DATA.categories, q = (s) => JSON.stringify(ascii(s || ""));
  const ent = [], th = [];
  for (const f of DATA.fws) {
    const cats = f.cats.reduce((m, c) => m | (1 << CATS.indexOf(c)), 0);
    let t = "NULL";
    if (f.t64 && THUMBS.has(f.id)) {
      const bytes = Uint8Array.from(atob(f.t64), (c) => c.charCodeAt(0));
      th.push(`static const uint8_t TH_${f.id.replace(/[^a-z0-9]/g, "_")}[512] = { ${Array.from(bytes).join(",")} };`);
      t = `TH_${f.id.replace(/[^a-z0-9]/g, "_")}`;
    }
    // (the mockup marks OLDVER's as updates even when the catalog has that version (KARMA 3.1.4): an older one here)
    const inst = INSTALLED0.has(f.id) ? q(OLDVER[f.id] ? (OLDVER[f.id] === f.ver ? "0.0.0" : OLDVER[f.id]) : f.ver) : "NULL";
    ent.push(`    { ${q(f.id)}, ${q(f.name)}, ${q(f.ver)}, ${inst}, ${q(f.what || f.tag)}, ${t}, ${cats}, ${CATS.indexOf(f.cat)}, ${f.t64 ? 1 : 0} },`);
  }
  writeFileSync(join(here, "move_fwb_data.h"), `/* generated by move_v2_ref.mjs from move-firmware-browser-mockup.html (remotefm1.com's catalog, ${DATA.generated}):
 * do not edit. The mockup's example: what is installed, the updates (OLDVER), the favourites (FAV0). */
${th.join("\n")}
typedef struct { const char *id, *name, *version, *installed, *desc; const uint8_t *thumb; uint8_t cats, cat, has_image; } fwb_ent_t;
static const fwb_ent_t FWB[] = {
${ent.join("\n")}
};
static const char *const FWB_FAV0[] = { ${FAV0.map((x) => JSON.stringify(x)).join(", ")} };
static const char *const FWB_NEWFW = ${JSON.stringify(NEWFW.id)};
`);
  console.log(rows.length, "firmware browser screens,", DATA.fws.length, "firmwares");
} else {
  // ---- the v2 design canvas
  let js = html.split('<script type="text/x-dc" data-dc-script')[1];
  js = js.slice(js.indexOf(">") + 1, js.lastIndexOf("</script>")).replace(/class Component[\s\S]*$/, "");
  const { S, W, H } = new Function(js + "\nreturn { S, W, H };")();
  const rows = [];
  for (const n of Object.keys(S)) {
    const b = new Uint8Array(W * H);
    S[n](b);
    rows.push(`    { "${n}", 0x${fnv(b).toString(16).padStart(8, "0")}u },`);
    if (process.argv[3]) writeFileSync(join(process.argv[3], `${n}.pbm`), pbm(b, W, H));
  }
  const out = `/* generated by move_v2_ref.mjs from the design canvas's V2Screen.dc.html: do not edit */
static const struct { const char *name; uint32_t hash; } V2_REF[] = {
${rows.join("\n")}
};
`;
  writeFileSync(join(here, "move_v2_ref.h"), out);
  console.log(rows.length, "screens");
}
